def _schema_errors(document: dict[str, Any]) -> list[str]:
    try:
        validator = Draft202012Validator(_schema())
    except SchemaError as exc:
        return [f"$: lock schema is invalid: {exc.message}"]
    found: list[str] = []
    for error in sorted(validator.iter_errors(document), key=_error_sort_key):
        if list(error.absolute_path) == ["layout_version"] and error.validator == "const":
            continue
        path = _json_path(error.absolute_path)
        found.append(f"{path}: {error.message}")
    return found


