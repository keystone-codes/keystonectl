def _split_managed_block(text: str) -> tuple[str, str | None]:
    start = text.find(_ENV_BLOCK_START)
    if start < 0:
        return text, None
    end = text.find(_ENV_BLOCK_END, start + len(_ENV_BLOCK_START))
    if end < 0:
        return text, None
    after = end + len(_ENV_BLOCK_END)
    if text[after : after + 1] == "\r":
        after += 1
    if text[after : after + 1] == "\n":
        after += 1
    return text[:start], text[after:]


