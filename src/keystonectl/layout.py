def _bind_mounts(root: Path, service: Mapping[str, Any]) -> list[tuple[Path, str]]:
    volumes = service.get("volumes")
    if not isinstance(volumes, list):
        return []
    mounts: list[tuple[Path, str]] = []
    for item in volumes:
        parsed = _parse_volume(item)
        if parsed is None:
            continue
        source, target = parsed
        mounts.append((_resolve_host_source(root, source), target))
    return mounts


def _parse_volume(item: object) -> tuple[str, str] | None:
    if isinstance(item, str):
        return _parse_short_volume(item)
    if isinstance(item, dict) and item.get("type") == "bind":
        source = item.get("source")
        target = item.get("target")
        if (
            isinstance(source, str)
            and isinstance(target, str)
            and source.startswith((".", "/", "~"))
        ):
            return source, target
    return None


def _parse_short_volume(spec: str) -> tuple[str, str] | None:
    source, sep, rest = spec.partition(":")
    if not sep or not source.startswith((".", "/", "~")):
        return None
    if ":" in rest:
        destination, mode = rest.rsplit(":", 1)
        if not _VOLUME_MODE.fullmatch(mode) or not destination.startswith("/"):
            destination = rest
    else:
        destination = rest
    if not destination.startswith("/"):
        return None
    return source, destination


def _map_container_path(mounts: Sequence[tuple[Path, str]], container_path: str) -> Path | None:
    target = container_path.rstrip("/") or "/"
    best: tuple[Path, str] | None = None
    best_len = -1
    for host, mount_target in mounts:
        normalized = mount_target.rstrip("/") or "/"
        if (target == normalized or target.startswith(normalized + "/")) and len(
            normalized
        ) > best_len:
            best = (host, normalized)
            best_len = len(normalized)
    if best is None:
        return None
    host, normalized = best
    if target == normalized:
        return host
    suffix = target[len(normalized) :].lstrip("/")
    return host / suffix


def _resolve_host_source(root: Path, source: str) -> Path:
    if source.startswith("~"):
        return Path(source).expanduser()
    path = Path(source)
    if path.is_absolute():
        return path
    return root / path


