def _inline_kind(raw: str) -> str:
    stripped = raw.strip()
    if stripped == "":
        return "blank"
    try:
        value = json.loads(stripped)
    except json.JSONDecodeError:
        return "invalid"
    if isinstance(value, list) and not value:
        return "empty_array"
    if isinstance(value, list):
        return "entries"
    return "invalid"


