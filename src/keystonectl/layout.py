def _interpolate(text: str, env: Mapping[str, str]) -> tuple[str, list[str]]:
    unset: list[str] = []

    def replace(match: re.Match[str]) -> str:
        if match.group("escaped") is not None:
            return "$"
        name = match.group("braced") or match.group("bare")
        assert name is not None
        op = match.group("op")
        arg = match.group("arg") or ""
        present = name in env
        value = env.get(name, "")
        if op is None:
            if not present:
                _remember(unset, name)
                return ""
            return value
        if op == ":-":
            if not present or value == "":
                return arg
            return value
        if op == "-":
            if not present:
                return arg
            return value
        if op == ":?":
            if not present or value == "":
                _remember(unset, name)
                return ""
            return value
        if op == "?":
            if not present:
                _remember(unset, name)
                return ""
            return value
        if op == ":+":
            return arg if present and value != "" else ""
        if op == "+":
            return arg if present else ""
        return match.group(0)

    return _INTERP.sub(replace, text), unset


def _remember(items: list[str], name: str) -> None:
    if name not in items:
        items.append(name)


def _parse_env_file(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        values[key] = value
    return values


