def _file_plan(
    root: Path,
    deployment: Deployment | None,
    inspection: _Inspection,
) -> tuple[list[tuple[str, int]], list[PlannedWrite], list[str]]:
    directories: list[tuple[str, int]] = []
    writes: list[PlannedWrite] = []
    actions: list[str] = []

    def want_dir(relative: str, mode: int) -> None:
        path = root / relative
        if path.is_dir() and (path.stat().st_mode & 0o777) == mode:
            return
        directories.append((relative, mode))
        actions.append(f"create:{relative}")

    def want_file(relative: str, content: str, mode: int) -> None:
        path = root / relative
        if (
            path.is_file()
            and path.read_bytes() == content.encode()
            and (path.stat().st_mode & 0o777) == mode
        ):
            return
        writes.append(PlannedWrite(relative, content, mode))
        actions.append(f"write:{relative}")

    want_dir("packages", _MODE_DIR)
    want_dir(KEYSTONECTL_DIR, _MODE_DIR)
    want_dir(".keystonectl", _MODE_PRIVATE_DIR)
    want_dir(".keystonectl/secrets", _MODE_PRIVATE_DIR)
    want_dir(".keystonectl/tmp", _MODE_PRIVATE_DIR)
    want_file(".keystonectl/.gitignore", "*\n", _MODE_FILE)
    if inspection.registry_text is not None:
        want_file(
            f"{KEYSTONECTL_DIR}/upstreams.yaml",
            inspection.registry_text,
            _MODE_FILE,
        )
    if inspection.snapshot_text is not None:
        want_file(
            f"{KEYSTONECTL_DIR}/catalog-snapshot.yaml",
            inspection.snapshot_text,
            _MODE_FILE,
        )
    if deployment is None:
        compose_text = _COMPOSE_HEADER + _dump_yaml(
            {
                "networks": {
                    UPSTREAMS_NETWORK: {
                        "name": UPSTREAMS_NETWORK,
                        "external": True,
                    }
                }
            }
        )
    else:
        compose_text = render_packages_compose(deployment)
    want_file(_PACKAGES_COMPOSE, compose_text, _MODE_FILE)
    gitignore = root / ".gitignore"
    if not gitignore.exists():
        want_file(".gitignore", _GITIGNORE, _MODE_FILE)
    return directories, writes, actions


def _lock_decision(root: Path, deployment: Deployment | None) -> tuple[bool, str | None]:
    existing = _read_lock(root)
    new_layout = None if deployment is None else deployment.to_dict()
    if existing is None:
        return True, None
    old_layout = existing.get("layout")
    changed = _changed_fields(old_layout, new_layout)
    if not changed:
        return False, None
    return True, "layout_changed: " + ", ".join(changed)


def _changed_fields(old: object, new: object) -> list[str]:
    if old is None and new is None:
        return []
    if old is None or new is None:
        return list(_LAYOUT_FIELDS)
    old_norm = _normalize_layout(old)
    new_norm = _normalize_layout(new)
    if not isinstance(old_norm, dict) or not isinstance(new_norm, dict):
        return list(_LAYOUT_FIELDS)
    return [field for field in _LAYOUT_FIELDS if old_norm.get(field) != new_norm.get(field)]


def _normalize_layout(value: object) -> object:
    if not isinstance(value, dict):
        return value
    data = dict(value)
    network = data.get("upstreams_network")
    if isinstance(network, dict):
        network = dict(network)
        if network.get("include_default_network") is False:
            network.pop("include_default_network", None)
        data["upstreams_network"] = network
    return data


def _preserve_mcp_version(deployment: Deployment, existing: dict[str, Any] | None) -> Deployment:
    if existing is None or deployment.keystone_mcp_version is not None:
        return deployment
    layout = existing.get("layout")
    if not isinstance(layout, dict):
        return deployment
    stored = layout.get("keystone_mcp_version")
    if not isinstance(stored, str) or not stored:
        return deployment
    if layout.get("keystone_image") != deployment.keystone_image:
        return deployment
    if layout.get("keystone_build") != deployment.keystone_build:
        return deployment
    network = dict(deployment.upstreams_network)
    return Deployment(
        flavor=deployment.flavor,
        project=deployment.project,
        compose_files=deployment.compose_files,
        keystone_service=deployment.keystone_service,
        profiles=deployment.profiles,
        keystone_image=deployment.keystone_image,
        keystone_build=deployment.keystone_build,
        keystone_mcp_version=stored,
        env_file=deployment.env_file,
        policy=deployment.policy,
        upstreams_network=network,
    )


