def _install_dir(path: Path, mode: int) -> bool:
    created = not path.is_dir()
    path.mkdir(parents=True, exist_ok=True)
    current = path.stat().st_mode & 0o777
    if current != mode:
        os.chmod(path, mode)
        return True
    return created


def _install_file(path: Path, content: str, mode: int) -> bool:
    data = content.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        if (path.stat().st_mode & 0o777) != mode:
            os.chmod(path, mode)
            return True
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write(path, data, mode)
    return True


def _atomic_write(path: Path, data: bytes, mode: int) -> None:
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{time.time_ns()}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    try:
        os.write(fd, data)
        os.fsync(fd)
    except Exception:
        os.close(fd)
        tmp.unlink(missing_ok=True)
        raise
    os.close(fd)
    os.chmod(tmp, mode)
    try:
        os.replace(tmp, path)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise
    dir_fd = os.open(path.parent, os.O_RDONLY)
    try:
        os.fsync(dir_fd)
    finally:
        os.close(dir_fd)


def _select_service(
    compose: Mapping[str, Any],
    keystone_service: str | None,
) -> tuple[str, dict[str, Any]]:
    services = compose.get("services")
    if not isinstance(services, dict):
        raise LayoutError(
            "keystone_service_not_found",
            "no service runs keystone-mcp; pass --keystone-service NAME if it is renamed",
            hint="pass --keystone-service NAME if the service was renamed",
        )
    if keystone_service is not None:
        selected = services.get(keystone_service)
        if not isinstance(selected, dict):
            raise LayoutError(
                "keystone_service_not_found",
                f"service {keystone_service!r} is not in the compose file; "
                "pass --keystone-service NAME if it is renamed",
                hint="pass the service name as it appears in the compose file",
            )
        return keystone_service, selected
    by_image = [
        name
        for name, spec in services.items()
        if isinstance(spec, dict) and _image_basename(spec.get("image")) == "keystone-mcp"
    ]
    if not by_image:
        by_image = [
            name
            for name, spec in services.items()
            if name == "keystone-mcp" and isinstance(spec, dict)
        ]
    if not by_image:
        raise LayoutError(
            "keystone_service_not_found",
            "no service runs keystone-mcp; pass --keystone-service NAME if it is renamed",
            hint="pass --keystone-service NAME if the service was renamed",
        )
    if len(by_image) > 1:
        raise LayoutError(
            "keystone_service_ambiguous",
            "more than one service runs keystone-mcp",
            hint="pass --keystone-service NAME",
            exit_code=2,
            choices=by_image,
        )
    name = by_image[0]
    spec = services[name]
    assert isinstance(spec, dict)
    return name, spec


def _image_basename(image: object) -> str | None:
    if not isinstance(image, str) or not image:
        return None
    without_digest = image.split("@", 1)[0]
    last = without_digest.rsplit("/", 1)[-1]
    if ":" in last:
        last = last.split(":", 1)[0]
    return last


